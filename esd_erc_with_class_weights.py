    # ------------------------------------------------------------------
    # Step 4: Train ESD-ERC
    # ------------------------------------------------------------------
    print("\n" + "="*60)
    print("  STEP 4: Training ESD-ERC (Main Model)")
    print("="*60)

    # Compute inverse-frequency class weights from training set
